import { forwardRef } from 'react';

/**
 * The print representation of a lesson.
 *
 * This is a completely separate render tree from the on-screen lesson, and that is the
 * point. It uses plain inline styles with literal hex colours and no Chakra components at
 * all, which buys three things:
 *
 *  1. Output is identical in light and dark mode. The live components read theme tokens;
 *     rasterising them would bake the user's current colour scheme into the PDF.
 *  2. Nothing depends on CSS custom properties or modern colour functions
 *     (oklch/lab/color-mix), which canvas rasterisers historically choke on.
 *  3. Width is pinned to A4 at 96dpi, so line breaks in the PDF are decided here rather
 *     than by whatever the browser window happens to be.
 *
 * Rendered off-screen (see LessonPDFExporter) and captured by ref.
 */

/** 210mm at 96dpi. */
export const PDF_WIDTH_PX = 794;

const COLORS = {
  text: '#1a202c',
  muted: '#4a5568',
  heading: '#111827',
  accent: '#4f46e5',
  accentBg: '#eef2ff',
  border: '#d1d5db',
  codeBg: '#f7fafc',
  codeText: '#1a202c',
  correctBg: '#f0fff4',
  correctBorder: '#9ae6b4',
};

const FONT = "'Inter', 'Helvetica Neue', Helvetica, Arial, sans-serif";
const MONO = "'JetBrains Mono', 'Courier New', Courier, monospace";

export const PdfLessonSheet = forwardRef(function PdfLessonSheet(
  { lesson, courseTitle, moduleTitle },
  ref,
) {
  if (!lesson) return null;

  let mcqNumber = 0;

  return (
    <div
      ref={ref}
      style={{
        width: `${PDF_WIDTH_PX}px`,
        padding: '48px 56px',
        background: '#ffffff',
        color: COLORS.text,
        fontFamily: FONT,
        fontSize: '14px',
        lineHeight: 1.7,
        boxSizing: 'border-box',
      }}
    >
      <header style={{ borderBottom: `2px solid ${COLORS.accent}`, paddingBottom: '16px', marginBottom: '28px' }}>
        <div style={{ fontSize: '11px', letterSpacing: '0.08em', textTransform: 'uppercase', color: COLORS.accent, fontWeight: 700 }}>
          {courseTitle}
          {moduleTitle ? ` · ${moduleTitle}` : ''}
        </div>
        <h1 style={{ margin: '10px 0 0', fontSize: '28px', lineHeight: 1.25, color: COLORS.heading, fontWeight: 700 }}>
          {lesson.title}
        </h1>
      </header>

      {lesson.objectives?.length > 0 && (
        <section
          style={{
            background: COLORS.accentBg,
            border: `1px solid ${COLORS.border}`,
            borderRadius: '8px',
            padding: '18px 22px',
            marginBottom: '28px',
          }}
        >
          <div style={{ fontWeight: 700, marginBottom: '10px', color: COLORS.heading }}>
            What you will learn
          </div>
          <ul style={{ margin: 0, paddingLeft: '20px' }}>
            {lesson.objectives.map((objective, index) => (
              <li key={index} style={{ marginBottom: '6px' }}>
                {objective}
              </li>
            ))}
          </ul>
        </section>
      )}

      {(lesson.content ?? []).map((block, index) => {
        if (!block || typeof block !== 'object') return null;
        if (block.type === 'mcq') mcqNumber += 1;
        return <PdfBlock key={index} block={block} number={mcqNumber} />;
      })}

      <footer
        style={{
          marginTop: '36px',
          paddingTop: '14px',
          borderTop: `1px solid ${COLORS.border}`,
          fontSize: '11px',
          color: COLORS.muted,
        }}
      >
        Generated by Text-to-Learn
      </footer>
    </div>
  );
});

function PdfBlock({ block, number }) {
  switch (block.type) {
    case 'heading':
      return (
        <h2
          style={{
            fontSize: block.level === 3 ? '17px' : '20px',
            color: COLORS.heading,
            fontWeight: 700,
            margin: '28px 0 12px',
            // Avoid a heading stranded at the foot of a page.
            breakAfter: 'avoid',
          }}
        >
          {block.text}
        </h2>
      );

    case 'paragraph':
      return <p style={{ margin: '0 0 14px' }}>{renderInlineForPdf(block.text)}</p>;

    case 'code':
      return (
        <pre
          style={{
            background: COLORS.codeBg,
            border: `1px solid ${COLORS.border}`,
            borderRadius: '6px',
            padding: '14px 16px',
            margin: '0 0 18px',
            fontFamily: MONO,
            fontSize: '12px',
            lineHeight: 1.6,
            color: COLORS.codeText,
            // Long lines must wrap: a PDF cannot be scrolled sideways.
            whiteSpace: 'pre-wrap',
            wordBreak: 'break-word',
            overflow: 'visible',
          }}
        >
          <code style={{ fontFamily: MONO }}>{block.text}</code>
        </pre>
      );

    case 'video':
      // A video cannot be printed, so the PDF carries the search link instead — the
      // offline reader can still find it.
      return (
        <p style={{ margin: '0 0 18px', fontSize: '12px', color: COLORS.muted }}>
          <strong>Suggested video:</strong> search YouTube for “{block.query}”
        </p>
      );

    case 'mcq':
      return (
        <div
          style={{
            border: `1px solid ${COLORS.border}`,
            borderRadius: '8px',
            padding: '16px 18px',
            margin: '0 0 16px',
            breakInside: 'avoid',
          }}
        >
          <div style={{ fontWeight: 700, marginBottom: '10px' }}>
            {number}. {block.question}
          </div>
          <ol style={{ margin: '0 0 10px', paddingLeft: '22px' }}>
            {(block.options ?? []).map((option, index) => {
              const isCorrect = index === Number(block.answer);
              return (
                <li
                  key={index}
                  style={{
                    marginBottom: '4px',
                    padding: isCorrect ? '2px 8px' : '2px 0',
                    background: isCorrect ? COLORS.correctBg : 'transparent',
                    border: isCorrect ? `1px solid ${COLORS.correctBorder}` : '1px solid transparent',
                    borderRadius: '4px',
                    fontWeight: isCorrect ? 600 : 400,
                  }}
                >
                  {option}
                  {isCorrect ? '  ✓' : ''}
                </li>
              );
            })}
          </ol>
          {block.explanation && (
            <div style={{ fontSize: '12px', color: COLORS.muted }}>
              <strong>Why:</strong> {block.explanation}
            </div>
          )}
        </div>
      );

    default:
      // Unknown types are skipped, matching the on-screen registry's contract.
      return null;
  }
}

/**
 * Inline markdown for print.
 *
 * Deliberately not shared with utils/markdown.jsx: that returns Chakra <Code> elements,
 * which would pull theme tokens into a tree that must stay theme-independent.
 */
function renderInlineForPdf(text) {
  const source = String(text ?? '');
  const segments = source.split(/(\*\*[^*]+\*\*|`[^`]+`)/g).filter(Boolean);

  return segments.map((segment, index) => {
    if (segment.startsWith('**') && segment.endsWith('**') && segment.length > 4) {
      return <strong key={index}>{segment.slice(2, -2)}</strong>;
    }
    if (segment.startsWith('`') && segment.endsWith('`') && segment.length > 2) {
      return (
        <code
          key={index}
          style={{
            fontFamily: MONO,
            fontSize: '0.92em',
            background: COLORS.codeBg,
            border: `1px solid ${COLORS.border}`,
            borderRadius: '3px',
            padding: '1px 4px',
          }}
        >
          {segment.slice(1, -1)}
        </code>
      );
    }
    return <span key={index}>{segment}</span>;
  });
}

export default PdfLessonSheet;
